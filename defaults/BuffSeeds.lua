-- defaults/BuffSeeds.lua — the buffs the Results Used column lists beside items, per client (CombatTrail
-- #13): world, zone, camp, shrine, faire and event buffs that move a fight's numbers the way a potion
-- does. Data only; CL-13b's fight-start aura walk reads it.
--
-- PICKED ONCE (clients-§5): the client's lists are chosen here, at FILE SCOPE, into NS.BUFF_SEEDS, and
-- nothing downstream asks which client it runs on again. Each client has its own lists, because their
-- spell ids and buffs differ (Camp Benefits and Might of Stormwind are WoW Forever's).
--
-- Each client's three lists are DERIVED from that client's own wago.tools build by three rules, which
-- tools/seeds/seeds.py runs (derive_buffs, derive_wellfed, derive_food):
--   buffs        every spell whose enUS name matches one of the tool's BUFF_CATALOG patterns in full
--                (case ignored) and that has a SpellEffect row putting an aura on a unit (Effect 6, 35,
--                65 or 128), at any DifficultyID. The catalog names the world buffs (Songflower,
--                Warchief's Blessing, Might of Stormwind, Rallying Cry of the Dragonslayer, Zandalar,
--                the Season of Discovery buffs), the Dire Maul tribute, Sayge's fortunes, the Silithus
--                and Blackfathom zone buffs, the Midsummer and Lunar Festival buffs, and Camp Benefits.
--                Every derived id is then ruled: one that changes no stat (WHEE!, experience) and one
--                whose source the data cannot show are left out.
--   wellFed      every aura spell named "Well Fed", or one word and "Well Fed" (Hearty Well Fed); plus
--                the buff a food gives under another name: for every Consumable of the Food & Drink
--                subclass, or whose use spell is Food, Drink, Refreshment or Food & Drink, the aura spells
--                its use spell triggers (one EffectTriggerSpell hop: Dirge's Kickin' Chimaerok Chops'
--                Increased Stamina 25661, Nightfin Soup's Mana Regeneration 18194), and the use spell
--                itself when it applies an aura other than an eating one (Dragonbreath Chili 15852). The
--                eating auras, Become Well Fed, test and [DNT] spells are left out, and every id is ruled:
--                one that changes no stat (a transform, a run speed, a heal over the meal) is rejected.
--                Buff food counts only through these auras, never through its Eat aura (#13's owner
--                comment).
--   foodSubclass the Consumable (item class 0) subclass that holds the most items whose use spell is
--                Food, Drink, Refreshment or Food & Drink: Food & Drink, 5 on both clients. A Consumable
--                of this subclass is never listed by its own Eat or Drink aura, cast or bag count.
-- The derived ids include the 1.x ids whose client DB2 carries a dummy aura where the server applies
-- the stats (Forever's Songflower Serenade 15366): kept, because matching an id that never shows up
