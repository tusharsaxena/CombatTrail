--- One of the active client's lists as a set, { [spellID] = true }: a fresh table per call.
--- @param list string "buffs" | "wellFed"
--- @return table
function NS.BuffSeedSet(list)
    local out = {}
    for _, id in ipairs(NS.BUFF_SEEDS[list] or {}) do out[id] = true end
    return out
end
